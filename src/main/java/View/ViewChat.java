    private void btnCambiarTemaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCambiarTemaActionPerformed
        try {
            // Verificar si el tema actual es oscuro
            if (com.formdev.flatlaf.FlatDarkLaf.isLafDark()) {
                // Si es oscuro, cambiar a claro de forma directa
                javax.swing.UIManager.setLookAndFeel(new com.formdev.flatlaf.FlatLightLaf());
                btnCambiarTema.setText("🌙 Modo Oscuro");
            } else {
                // Si es claro, cambiar a oscuro de forma directa
                javax.swing.UIManager.setLookAndFeel(new com.formdev.flatlaf.FlatDarkLaf());
                btnCambiarTema.setText("☀️ Modo Claro");
            }

            // Actualizar la interfaz gráfica de toda la ventana abierta
            javax.swing.SwingUtilities.updateComponentTreeUI(this);

        } catch (UnsupportedLookAndFeelException ex) {
        }
    }//GEN-LAST:event_btnCambiarTemaActionPerformed

