    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       String segundoTelefono = javax.swing.JOptionPane.showInputDialog(this, "Ingrese el segundo número de teléfono (10 dígitos):", "Teléfono Adicional", javax.swing.JOptionPane.QUESTION_MESSAGE);
        
        if (segundoTelefono != null && !segundoTelefono.trim().isEmpty()) {
            String telActual = jTextField4.getText();
            if (telActual.equals("10 digitos") || telActual.isEmpty()) {
                jTextField4.setText(segundoTelefono);
            } else {
                jTextField4.setText(telActual + " / " + segundoTelefono);
            }
            javax.swing.JOptionPane.showMessageDialog(this, "¡Teléfono adicional agregado!");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

