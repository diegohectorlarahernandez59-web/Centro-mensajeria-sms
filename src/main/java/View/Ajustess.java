    private void btnEnviar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnviar1ActionPerformed
       String asunto = txtAsunto.getText().trim();
    String mensaje = txtMensaje.getText().trim();

    if (asunto.isEmpty() || mensaje.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Escribe el asunto y el mensaje.",
                "Campos vacíos", JOptionPane.WARNING_MESSAGE);
        return;
    
    }//GEN-LAST:event_btnEnviar1ActionPerformed
// Se guarda para que el administrador lo vea en "Mensajes técnicos"
    mensajesTecnicos.add(new String[]{asunto, mensaje});

    JOptionPane.showMessageDialog(this, "Mensaje enviado al servicio técnico.");
    txtAsunto.setText("");
    txtMensaje.setText("");
    txtAsunto.requestFocus();
    }
