    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
    String nombres = txtNombres.getText().trim();
    String apellidos = txtApellidos.getText().trim();
    String direccion = txtDireccion.getText().trim();
    String correo = txtCorreoAjustes.getText().trim();

    if (nombres.isEmpty() || apellidos.isEmpty() || direccion.isEmpty() || correo.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Completa todos los campos.",
                "Campos vacíos", JOptionPane.WARNING_MESSAGE);
        return;
        
    }//GEN-LAST:event_btnGuardarActionPerformed
 if (!correo.matches("^[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+$")) {
        JOptionPane.showMessageDialog(this, "El correo no es válido.",
                "Error", JOptionPane.ERROR_MESSAGE);
        txtCorreoAjustes.requestFocus();
        return;
 }
   int confirmar = JOptionPane.showConfirmDialog(this,
            "¿Guardar los cambios?", "Confirmar", JOptionPane.YES_NO_OPTION);

    if (confirmar == JOptionPane.YES_OPTION) {
        // Aquí iría el guardado real (archivo o base de datos)
        JOptionPane.showMessageDialog(this, "Información actualizada correctamente.");
    }}
